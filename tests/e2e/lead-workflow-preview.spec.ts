import {test,expect} from '@playwright/test';
test('existing AIRE screens persist synthetic prospect, service and hold paths with replay and permissions',async({page,context})=>{
  test.setTimeout(90000);
  await page.setViewportSize({width:1440,height:1000});
  const external:string[]=[];
  await context.route('**/*',async route=>{const url=new URL(route.request().url());if(!['127.0.0.1','localhost'].includes(url.hostname)){external.push(url.origin);await route.abort();}else await route.continue();});
  await page.goto('/lead-preview');
  await page.getByRole('button',{name:'Open synthetic operator',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Incoming leads',exact:true})).toBeVisible();
  await expect(page.getByText('3 records · source history retained')).toBeVisible();
  const demo=page.getByRole('row').filter({hasText:'Alex · synthetic demo'});
  await demo.getByRole('button',{name:'Review',exact:true}).click();
  const drawer=page.getByRole('complementary',{name:'Quick review for Alex · synthetic demo'});
  await drawer.getByRole('combobox',{name:'Classification',exact:true}).selectOption('GENUINE_PROSPECT');
  await drawer.getByLabel('Reason (required)',{exact:true}).fill('Synthetic demo submission reviewed: resolved identity and Event Suite fit.');
  await drawer.getByRole('button',{name:'Save classification',exact:true}).click();
  await expect(drawer).toHaveCount(0);
  await page.getByLabel('Dismiss confirmation').click();
  await demo.getByRole('button',{name:'Review',exact:true}).click();
  await drawer.getByRole('combobox',{name:'Work owner',exact:true}).selectOption({label:'Alex · synthetic owner'});
  await drawer.getByLabel('Recorded next action',{exact:true}).fill('Prepare offline Event Suite demo brief');
  await drawer.getByLabel('Follow-up due',{exact:true}).fill('2026-11-18T10:00');
  await drawer.getByRole('button',{name:'Save work plan',exact:true}).click();
  await expect(drawer.getByLabel('Recorded next action')).toHaveValue('Prepare offline Event Suite demo brief');
  await drawer.getByLabel('Decision evidence').fill('Synthetic source shows Event Suite fit; owner reviewed this request.');
  await drawer.getByRole('button',{name:'Link justified opportunity',exact:true}).click();
  await expect(drawer.getByText('Linked opportunity: identified',{exact:true})).toBeVisible();
  await drawer.getByRole('combobox',{name:'Next opportunity stage',exact:true}).selectOption('qualified');
  await drawer.getByLabel('Decision evidence').fill('Synthetic requirements verified against the retained demo submission.');
  await drawer.getByRole('button',{name:'Record opportunity progression',exact:true}).click();
  await expect(drawer.getByText('Linked opportunity: qualified',{exact:true})).toBeVisible();
  await drawer.locator('.incoming-drawer-scroll').evaluate(el=>{const plan=el.querySelector('.lead-work-plan')!;el.scrollTop+=plan.getBoundingClientRect().top-el.getBoundingClientRect().top;});
  await page.screenshot({path:'test-results/lead-workflow-plan.png',fullPage:true});
  await drawer.getByText('Notes and audit history',{exact:true}).click();
  await expect(drawer.getByText(/PROGRESS OPPORTUNITY/)).toBeVisible();
  await page.screenshot({path:'test-results/lead-workflow-prospect.png',fullPage:true});
  const state=await page.evaluate(async()=>{
    const list=await(await fetch('/api/incoming-leads?view=all')).json();
    const lead=list.leads.find((l:any)=>l.display_name==='Alex · synthetic demo');
    const detail=await(await fetch(`/api/incoming-leads?leadId=${lead.id}`)).json();
    const replay=await(await fetch('/api/incoming-leads',{method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify({action:'PREVIEW_RECEIVE',scenario:'demo'})})).json();
    return {lead,detail,replay};
  });
  expect(state.replay.duplicate).toBe(true);expect(state.replay.lead_id).toBe(state.lead.id);
  expect(state.detail.submissions).toHaveLength(1);expect(state.detail.activities).toHaveLength(1);
  expect(state.detail.lead.last_contacted_at).toBeNull();expect(state.detail.opportunity.stage).toBe('qualified');
  expect(state.detail.changes.some((c:any)=>c.action==='PROGRESS_OPPORTUNITY'&&c.actor_id&&c.new_values.opportunity.stage==='qualified')).toBe(true);
  await page.reload();await expect(demo).toContainText('Prepare offline Event Suite demo brief');
  await expect(demo).toContainText('Qualified');
  await page.getByRole('row').filter({hasText:'Sam · synthetic trial'}).getByRole('button',{name:'Review',exact:true}).click();
  const trial=page.getByRole('complementary',{name:'Quick review for Sam · synthetic trial'});
  await expect(trial.getByRole('heading',{name:'Customer / trial service follow-up'})).toBeVisible();
  await expect(trial.getByRole('button',{name:'Link justified opportunity'})).toBeDisabled();
  await trial.getByRole('combobox',{name:'Work owner',exact:true}).selectOption({label:'Alex · synthetic owner'});
  await trial.getByLabel('Recorded next action').fill('Review synthetic trial activation evidence');
  await trial.getByLabel('Follow-up due').fill('2026-11-18T11:00');
  await trial.getByRole('button',{name:'Save work plan',exact:true}).click();
  await expect(trial.getByLabel('Recorded next action')).toHaveValue('Review synthetic trial activation evidence');
  await page.getByLabel('Close quick review').click();
  await page.getByRole('row').filter({hasText:'Jordan · synthetic review'}).getByRole('button',{name:'Review',exact:true}).click();
  const held=page.getByRole('complementary',{name:'Quick review for Jordan · synthetic review'});
  await held.getByText('Hold and review condition',{exact:true}).click();
  await held.getByLabel('Hold reason',{exact:true}).fill('Ambiguous account: no authoritative organisation match');
  await held.getByLabel('Next review condition').fill('Review when the product owner provides identity evidence');
  await held.getByLabel('Review date',{exact:true}).fill('2026-11-19T09:00');
  await held.getByRole('button',{name:'Save hold',exact:true}).click();
  await expect(held.getByText('On hold: Ambiguous account: no authoritative organisation match',{exact:true})).toBeVisible();
  await page.screenshot({path:'test-results/lead-workflow-held.png',fullPage:true});
  await page.getByLabel('Close quick review').click();
  await page.getByText('More filters',{exact:true}).click();
  await page.getByRole('combobox',{name:'Owner',exact:true}).selectOption('UNASSIGNED');
  await expect(page.getByText('1 records · source history retained')).toBeVisible();
  await page.screenshot({path:'test-results/lead-workflow-unassigned.png',fullPage:true});
  await page.goto('/lead-preview');await page.getByRole('button',{name:'Open read-only viewer',exact:true}).click();
  await expect(page.getByText('Viewers can inspect evidence and history but cannot change classification, ownership or follow-up.')).toBeVisible();
  const denied=await page.evaluate(async id=>(await fetch('/api/incoming-leads',{method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify({leadId:id,action:'SET_NEXT_ACTION',value:{nextAction:'Forbidden viewer write'}})})).status,state.lead.id);
  expect(denied).toBe(403);
  await context.clearCookies();
  expect((await page.request.get('/api/incoming-leads')).status()).toBe(401);
  expect((await page.request.get('/api/ai-sales/discovery')).status()).toBe(404);
  expect(external).toEqual([]);
});
